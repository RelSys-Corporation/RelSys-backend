CREATE TABLE PRODUCT_SUPPLIER (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRODUCT_ID BIGINT NOT NULL,
    SUPPLIER_ID BIGINT NOT NULL,
    DISCOUNT_ALLOWED BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PRODUCT_SUPPLIER_ID PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUCT_SUPPLIER_TO_PRODUCT_ID FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID),
    CONSTRAINT FK_PRODUCT_SUPPLIER_TO_SUPPLIER_ID FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIER (ID),
    CONSTRAINT UQ_PRODUCT_SUPPLIER_TO_PRODUCT_ID_AND_SUPPLIER_ID UNIQUE (PRODUCT_ID, SUPPLIER_ID)
