/* SYSTEM MANAGEMENT */
CREATE TABLE SYSTEM.COMPANY (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CORPORATE_NAME VARCHAR(200) NOT NULL,
    TRADE_NAME VARCHAR(200),
    IS_HEADQUARTER BOOLEAN NOT NULL DEFAULT FALSE,
    HEADQUARTER_COMPANY_ID BIGINT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_COMPANY_TO_ID PRIMARY KEY (ID),
    CONSTRAINT FK_COMPANY_TO_HEADQUARTER_COMPANY_ID FOREIGN KEY (HEADQUARTER_COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT UQ_COMPANY_TO_NAME UNIQUE (CORPORATE_NAME)
);

CREATE TABLE SYSTEM.MODULE (
