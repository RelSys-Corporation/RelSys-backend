CREATE SCHEMA IF NOT EXISTS SYSTEM;
CREATE SCHEMA IF NOT EXISTS AUTH;
CREATE SCHEMA IF NOT EXISTS REVENUE;
CREATE SCHEMA IF NOT EXISTS FINANCIAL;


CREATE TABLE SYSTEM.COMPANY (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CORPORATE_NAME VARCHAR(200) NOT NULL,
    TRADE_NAME VARCHAR(200),
    IS_HEADQUARTER BOOLEAN NOT NULL DEFAULT FALSE,
    HEADQUARTER_COMPANY_ID BIGINT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_COMPANY_ID PRIMARY KEY (ID),
    CONSTRAINT FK_COMPANY_TO_HEADQUARTER FOREIGN KEY (HEADQUARTER_COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT UQ_COMPANY_TO_NAME UNIQUE (CORPORATE_NAME)
);

