CREATE TABLE REVENUE.SALE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_ID BIGINT NOT NULL,
    CLIENT_ID BIGINT,
    PAYMENT_METHOD_ID BIGINT NOT NULL,
    DISCOUNT_PERCENTAGE NUMERIC(5,2) NOT NULL DEFAULT 0,
    SALE_STATUS_ID BIGINT NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_SALE_ID PRIMARY KEY (ID),
    CONSTRAINT FK_SALE_TO_COMPANY_ID FOREIGN KEY (COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT FK_SALE_TO_CLIENT_ID FOREIGN KEY (CLIENT_ID) REFERENCES REVENUE.CLIENT (ID),
