/* ENTERPRISE RESOURCE PLANNING */
CREATE TABLE REVENUE.PERSON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_ID BIGINT NOT NULL,
    NAME VARCHAR(200) NOT NULL,
    EMAIL VARCHAR(255),
    PERSON_TYPE_ACRONYM VARCHAR(2) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PERSON_ID PRIMARY KEY (ID),
    CONSTRAINT FK_PERSON_TO_COMPANY_ID FOREIGN KEY (COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT UQ_PERSON_TO_ID_AND_PERSON_TYPE_ACRONYM UNIQUE (ID, PERSON_TYPE_ACRONYM),
    CONSTRAINT UQ_PERSON_TO_EMAIL UNIQUE (COMPANY_ID, EMAIL),
    CONSTRAINT CK_PERSON_TO_PERSON_TYPE_ACRONYM CHECK (PERSON_TYPE_ACRONYM IN ('P', 'L', 'D')) -- PHYSICAL, LEGAL, DIGITAL
);

CREATE TABLE REVENUE.PHYSICAL_PERSON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_ID BIGINT NOT NULL,
    PERSON_ID BIGINT NOT NULL,
    PERSON_TYPE_ACRONYM VARCHAR(2) GENERATED ALWAYS AS ('P') STORED,
    CPF VARCHAR(11) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PHYSICAL_PERSON_ID PRIMARY KEY (ID),
    CONSTRAINT FK_PHYSICAL_PERSON_TO_COMPANY_ID FOREIGN KEY (COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT FK_PHYSICAL_PERSON_TO_PERSON_ID_AND_PERSON_TYPE_ACRONYM FOREIGN KEY (PERSON_ID, PERSON_TYPE_ACRONYM) REFERENCES REVENUE.PERSON (ID, PERSON_TYPE_ACRONYM),
    CONSTRAINT UQ_PHYSICAL_PERSON_TO_PERSON_ID UNIQUE (COMPANY_ID, PERSON_ID),
    CONSTRAINT UQ_PHYSICAL_PERSON_TO_CPF UNIQUE (COMPANY_ID, CPF),
    CONSTRAINT CK_PHYSICAL_PERSON_TO_CPF CHECK (LENGTH(CPF) = 11)
);

CREATE TABLE REVENUE.LEGAL_PERSON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_ID BIGINT NOT NULL,
    PERSON_ID BIGINT NOT NULL,
    PERSON_TYPE_ACRONYM VARCHAR(2) GENERATED ALWAYS AS ('L') STORED,
    CNPJ VARCHAR(14) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_LEGAL_PERSON_ID PRIMARY KEY (ID),
    CONSTRAINT FK_LEGAL_PERSON_TO_COMPANY_ID FOREIGN KEY (COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT FK_LEGAL_PERSON_TO_PERSON_ID_AND_PERSON_TYPE_ACRONYM FOREIGN KEY (PERSON_ID, PERSON_TYPE_ACRONYM) REFERENCES REVENUE.PERSON (ID, PERSON_TYPE_ACRONYM),
    CONSTRAINT UQ_LEGAL_PERSON_TO_PERSON_ID UNIQUE (COMPANY_ID, PERSON_ID),
    CONSTRAINT UQ_LEGAL_PERSON_TO_CNPJ UNIQUE (COMPANY_ID, CNPJ),
    CONSTRAINT CK_LEGAL_PERSON_TO_CNPJ CHECK (LENGTH(CNPJ) = 14)
);

