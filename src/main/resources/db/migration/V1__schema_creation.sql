/* AUTHENTICATION */
CREATE TABLE PERMISSIONS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR(100) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PERMISSIONS_ID PRIMARY KEY (ID),
    CONSTRAINT UQ_PERMISSIONS_TO_NAME UNIQUE (NAME)
);

CREATE TABLE ROLES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR(100) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_ROLES_ID PRIMARY KEY (ID),
    CONSTRAINT UQ_ROLES_TO_NAME UNIQUE (NAME)
);

CREATE TABLE ROLES_PERMISSIONS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ROLE_ID BIGINT NOT NULL,
    PERMISSION_ID BIGINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_ROLES_PERMISSIONS_ID PRIMARY KEY (ID),
    CONSTRAINT FK_ROLES_PERMISSIONS_TO_ROLES_ID FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID),
    CONSTRAINT FK_ROLES_PERMISSIONS_TO_PERMISSIONS_ID FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS(ID),
    CONSTRAINT UQ_ROLES_PERMISSIONS_TO_ROLE_ID_AND_PERMISSION_ID UNIQUE (ROLE_ID, PERMISSION_ID)
);

CREATE TABLE USERS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR(100) NOT NULL,
    ROLE_ID BIGINT NOT NULL,
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_USERS_ID PRIMARY KEY (ID),
    CONSTRAINT FK_USERS_TO_ROLES_ID FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID),
    CONSTRAINT UQ_USERS_TO_NAME UNIQUE (NAME)
);





/* ENTERPRISE RESOURCE PLANNING */
CREATE TABLE PERSON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR(200) NOT NULL,
    EMAIL VARCHAR(255),
    PERSON_TYPE_ACRONYM VARCHAR(2),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PERSON_ID PRIMARY KEY (ID),
    CONSTRAINT UQ_PERSON_TO_ID_PERSON_TYPE_ACRONYM UNIQUE (ID, PERSON_TYPE_ACRONYM),
    CONSTRAINT UQ_PERSON_TO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_PERSON_TO_PERSON_TYPE_ACRONYM CHECK (PERSON_TYPE_ACRONYM IN ('F', 'J'))
);

CREATE TABLE PHYSICAL_PERSON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PERSON_ID BIGINT NOT NULL,
    PERSON_TYPE_ACRONYM VARCHAR(2) GENERATED ALWAYS AS ('F') STORED,
    CPF VARCHAR(11) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PHYSICAL_PERSON_ID PRIMARY KEY (ID),
    CONSTRAINT FK_PHYSICAL_PERSON_TO_PERSON_ID_AND_PERSON_TYPE_ACRONYM FOREIGN KEY (PERSON_ID, PERSON_TYPE_ACRONYM) REFERENCES PERSON (ID, PERSON_TYPE_ACRONYM),
    CONSTRAINT UQ_PHYSICAL_PERSON_TO_PERSON_ID UNIQUE (PERSON_ID),
    CONSTRAINT UQ_PHYSICAL_PERSON_TO_CPF UNIQUE (CPF),
    CONSTRAINT CK_PHYSICAL_PERSON_TO_CPF CHECK (LENGTH(CPF) = 11)
);

CREATE TABLE LEGAL_PERSON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PERSON_ID BIGINT NOT NULL,
    PERSON_TYPE_ACRONYM VARCHAR(2) GENERATED ALWAYS AS ('J') STORED,
    CNPJ VARCHAR(14) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_LEGAL_PERSON_ID PRIMARY KEY (ID),
    CONSTRAINT FK_LEGAL_PERSON_TO_PERSON_ID_AND_PERSON_TYPE_ACRONYM FOREIGN KEY (PERSON_ID, PERSON_TYPE_ACRONYM) REFERENCES PERSON (ID, PERSON_TYPE_ACRONYM),
    CONSTRAINT UQ_LEGAL_PERSON_TO_PERSON_ID UNIQUE (PERSON_ID),
    CONSTRAINT UQ_LEGAL_PERSON_TO_CNPJ UNIQUE (CNPJ),
    CONSTRAINT CK_LEGAL_PERSON_TO_CNPJ CHECK (LENGTH(CNPJ) = 14)
);

CREATE TABLE PERSON_STATUS (
