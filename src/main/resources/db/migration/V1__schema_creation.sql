CREATE TABLE REVENUE.PRODUCT_BATCH (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_ID BIGINT NOT NULL,
    PRODUCT_SUPPLIER_ID BIGINT NOT NULL,
    PURCHASE_PRICE NUMERIC(15,3) NOT NULL,
    PURCHASE_QUANTITY NUMERIC(15,3) NOT NULL,
    REMAINING_QUANTITY NUMERIC(15,3) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PRODUCT_BATCH_ID PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUCT_BATCH_TO_COMPANY_ID FOREIGN KEY (COMPANY_ID) REFERENCES SYSTEM.COMPANY (ID),
    CONSTRAINT FK_PRODUCT_BATCH_TO_PRODUCT_SUPPLIER_ID FOREIGN KEY (PRODUCT_SUPPLIER_ID) REFERENCES REVENUE.PRODUCT_SUPPLIER (ID),
    CONSTRAINT CK_PRODUCT_BATCH_TO_PURCHASE_PRICE CHECK (PURCHASE_PRICE >= 0),
    CONSTRAINT CK_PRODUCT_BATCH_TO_PURCHASE_QUANTITY CHECK (PURCHASE_QUANTITY > 0),
    CONSTRAINT CK_PRODUCT_BATCH_TO_REMAINING_QUANTITY CHECK (REMAINING_QUANTITY >= 0),
    CONSTRAINT CK_PRODUCT_BATCH_TO_PURCHASE_QUANTITY_AND_REMAINING_QUANTITY CHECK (REMAINING_QUANTITY <= PURCHASE_QUANTITY)
);

