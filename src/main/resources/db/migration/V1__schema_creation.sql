                          ('AUTH');

CREATE TABLE SYSTEM.SCREEN (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR(200) NOT NULL,
    MODULE_ID BIGINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_SCREEN_TO_ID PRIMARY KEY (ID),
    CONSTRAINT FK_SCREEN_TO_MODULE_ID FOREIGN KEY (MODULE_ID) REFERENCES SYSTEM.MODULE (ID),
    CONSTRAINT UQ_SCREEN_TO_NAME UNIQUE (NAME)
);

WITH TARGET(SCREEN_NAME, MODULE_NAME) AS (
    VALUES
        ('POS_TERMINAL', 'REVENUE'),
        ('MANAGE_PRODUCT', 'REVENUE'),
        ('RECEIVE_PRODUCT_BATCH', 'REVENUE'),
        ('MANAGE_PERSON', 'REVENUE'),
        ('MANAGE_ROLE', 'AUTH'),
        ('MANAGE_USER', 'AUTH'),
        ('MANAGE_COMPANY', 'SYSTEM')
)
INSERT INTO SYSTEM.SCREEN (NAME, MODULE_ID)
SELECT T.SCREEN_NAME,
       M.ID
  FROM TARGET T
  JOIN SYSTEM.MODULE M ON (M.NAME = T.MODULE_NAME);

