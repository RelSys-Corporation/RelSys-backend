CREATE TABLE SALE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CLIENT_ID BIGINT,
    PAYMENT_METHOD_ID BIGINT NOT NULL,
    DISCOUNT_PERCENTAGE NUMERIC(5,2) NOT NULL DEFAULT 0,
    SALE_STATUS_ID BIGINT NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_SALE_ID PRIMARY KEY (ID),
    CONSTRAINT FK_SALE_TO_CLIENT_ID FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT (ID),
    CONSTRAINT FK_SALE_TO_PAYMENT_METHOD_ID FOREIGN KEY (PAYMENT_METHOD_ID) REFERENCES PAYMENT_METHOD (ID),
    CONSTRAINT FK_SALE_TO_SALE_STATUS_ID FOREIGN KEY (SALE_STATUS_ID) REFERENCES SALE_STATUS (ID),
    CONSTRAINT CK_SALE_TO_DISCOUNT_PERCENTAGE CHECK (DISCOUNT_PERCENTAGE >= 0 AND DISCOUNT_PERCENTAGE <= 100)
);

CREATE TABLE PRODUCT_SALE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SALE_ID BIGINT NOT NULL,
    PRODUCT_ID BIGINT NOT NULL,
    QUANTITY NUMERIC(15,3) NOT NULL,
    DISCOUNT_PERCENTAGE NUMERIC(5,2) NOT NULL DEFAULT 0,
    PRODUCT_NAME VARCHAR(100) NOT NULL,
    PRODUCT_PRICE NUMERIC(15,3) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_PRODUCT_SALE_ID PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUCT_SALE_TO_SALE_ID FOREIGN KEY (SALE_ID) REFERENCES SALE (ID),
    CONSTRAINT FK_PRODUCT_SALE_TO_PRODUCT_ID FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID),
    CONSTRAINT UQ_PRODUCT_SALE_TO_SALE_ID_AND_PRODUCT_ID UNIQUE (SALE_ID, PRODUCT_ID),
    CONSTRAINT CK_PRODUCT_SALE_TO_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CK_PRODUCT_SALE_TO_DISCOUNT_PERCENTAGE CHECK (DISCOUNT_PERCENTAGE >= 0 AND DISCOUNT_PERCENTAGE <= 100)
);

CREATE TABLE PRODUCT_SALE_BATCH (
